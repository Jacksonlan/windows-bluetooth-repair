<#
.SYNOPSIS
    Installs a boot-time self-healing guard that repairs a flaky Bluetooth radio
    automatically, so the user never has to run the repair by hand again.

.DESCRIPTION
    Writes a guard script to %ProgramData%\BTGuard\bt-guard.ps1 and registers a
    scheduled task that runs it at every boot as SYSTEM with the highest
    privileges, after a short delay so the USB stack is ready.

    The guard is a no-op when the radio is healthy: it checks the device status,
    and only if the status is not OK does it perform disable -> enable cycles.
    Consequences: zero runtime cost on healthy boots, no side effects, fully
    automatic recovery on broken boots.

.PARAMETER TaskName
    Scheduled task name. Default BTGuardAutoRepair.

.PARAMETER Root
    Working directory for the guard script and log. Default C:\ProgramData\BTGuard

.PARAMETER DevicePattern
    Wildcard matching the radio instance ID. Default is auto-derived from the
    currently enumerated Bluetooth radio (vendor + product ID).

.PARAMETER DelaySeconds
    Boot delay before the guard runs. Default 25.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File install-guard.ps1
#>
[CmdletBinding()]
param(
    [string]$TaskName = 'BTGuardAutoRepair',
    [string]$Root = 'C:\ProgramData\BTGuard',
    [string]$DevicePattern,
    [int]$DelaySeconds = 25
)

$ErrorActionPreference = 'Continue'
$ProgressPreference = 'SilentlyContinue'
$log = Join-Path $env:TEMP 'bt-install-log.txt'
function L([string]$m) {
    $line = "{0}  {1}" -f (Get-Date).ToString('HH:mm:ss'), $m
    $line | Out-File -FilePath $log -Append -Encoding utf8
    Write-Host $line
}
"" | Out-File $log -Encoding utf8

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
L "Elevated = $isAdmin"
if (-not $isAdmin) {
    L "ABORT: must run as administrator. Use run-elevated.bat install-guard.ps1"
    exit 2
}

# ------------------------------------------------- derive device pattern
if (-not $DevicePattern) {
    $radio = Get-PnpDevice -Class Bluetooth -PresentOnly -ErrorAction SilentlyContinue |
        Where-Object { $_.InstanceId -like 'USB\*' } | Select-Object -First 1
    if (-not $radio) {
        L "ABORT: no USB Bluetooth radio present, cannot derive a device pattern."
        L "       Pass -DevicePattern explicitly, e.g. 'USB\VID_8087&PID_0029*'."
        exit 1
    }
    $parts = $radio.InstanceId -split '\\'
    $DevicePattern = ($parts[0..1] -join '\') + '*'
    L "Detected radio : $($radio.FriendlyName)  [$($radio.InstanceId)]"
}
L "Device pattern : $DevicePattern"

# ------------------------------------------------------ guard script body
$guardFile = Join-Path $Root 'bt-guard.ps1'
New-Item -ItemType Directory -Path $Root -Force | Out-Null

$body = @'
# Auto-generated by windows-bluetooth-repair skill. Do not edit by hand.
$ErrorActionPreference = "Continue"
$logDir  = "C:\ProgramData\BTGuard"
$logFile = Join-Path $logDir "bt-guard.log"
$pattern = "__PATTERN__"
if (-not (Test-Path $logDir)) { New-Item -ItemType Directory -Path $logDir -Force | Out-Null }

# keep the log from growing without bound
if ((Test-Path $logFile) -and ((Get-Item $logFile).Length -gt 1MB)) {
    Move-Item $logFile ($logFile + ".old") -Force
}

function W($m) { "$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')  $m" | Out-File $logFile -Append -Encoding utf8 }

function Get-Radio {
    $c = @(Get-PnpDevice -Class Bluetooth -PresentOnly -ErrorAction SilentlyContinue |
        Where-Object { $_.InstanceId -like $pattern })
    if ($c.Count -eq 0) { return $null }
    return ($c | Select-Object -First 1)
}

$dev = $null
for ($i = 0; $i -lt 40; $i++) {
    $dev = Get-Radio
    if ($dev) { break }
    Start-Sleep -Seconds 2
}
if (-not $dev) { W "adapter never enumerated within 80s - giving up (check hardware/BIOS)"; exit 0 }

W "boot check: Status=$($dev.Status) Problem=$($dev.Problem)"
if ($dev.Status -eq "OK") { W "healthy - no action"; exit 0 }

for ($try = 1; $try -le 3; $try++) {
    W "repair attempt $try -> $($dev.InstanceId)"
    try { Disable-PnpDevice -InstanceId $dev.InstanceId -Confirm:$false -ErrorAction Stop }
    catch { W "  disable error: $($_.Exception.Message)" }
    Start-Sleep -Seconds 3
    try { Enable-PnpDevice -InstanceId $dev.InstanceId -Confirm:$false -ErrorAction Stop }
    catch { W "  enable error: $($_.Exception.Message)" }
    Start-Sleep -Seconds 6
    $dev = Get-Radio
    if (-not $dev) { W "  device missing after attempt $try"; continue }
    W "  after attempt $try : Status=$($dev.Status) Problem=$($dev.Problem)"
    if ($dev.Status -eq "OK") { break }
}

try { Start-Service bthserv -ErrorAction Stop; W "bthserv started" } catch { }

Get-CimInstance -Namespace root\wmi -ClassName MSPower_DeviceEnable -ErrorAction SilentlyContinue |
    Where-Object { $_.Enable -and ($_.InstanceName -like "*$($pattern.Split("\")[1])*") } |
    ForEach-Object {
        try { $_.Enable = $false; Set-CimInstance -InputObject $_ -ErrorAction Stop; W "power-save re-disabled: $($_.InstanceName)" }
        catch { }
    }

$f = Get-Radio
W "done (final: $($f.Status))"
'@

$body = $body.Replace('__PATTERN__', $DevicePattern)
$body | Out-File -FilePath $guardFile -Encoding utf8 -Force
L "Guard script   : $guardFile"

# allow normal users to read the log for troubleshooting
& icacls.exe $Root /grant "Users:(OI)(CI)R" /T /C 2>&1 | Out-Null

# ---------------------------------------------------- register the task
L "Registering scheduled task '$TaskName'"
try {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue

    $action = New-ScheduledTaskAction -Execute 'powershell.exe' `
        -Argument ('-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "{0}"' -f $guardFile)
    $trigger = New-ScheduledTaskTrigger -AtStartup
    try { $trigger.Delay = ('PT{0}S' -f $DelaySeconds) } catch { L "  (delay unsupported, guard waits internally)" }

    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
        -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
    $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest

    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
        -Principal $principal -Description 'Self-healing guard for a flaky Bluetooth radio' -Force | Out-Null

    $t = Get-ScheduledTask -TaskName $TaskName
    L "  state   : $($t.State)"
    L "  run as  : $($t.Principal.UserId) / $($t.Principal.RunLevel)"
    L "  delay   : $($t.Triggers[0].Delay)"

    # Marker lets a NON-admin diagnostic run see that the guard exists, because
    # a SYSTEM task is not reliably enumerable without elevation.
    $marker = Join-Path $Root 'installed.json'
    $info = [ordered]@{
        TaskName      = $TaskName
        DevicePattern = $DevicePattern
        DelaySeconds  = $DelaySeconds
        InstalledAt   = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
        Machine       = $env:COMPUTERNAME
        GuardFile     = $guardFile
    }
    ($info | ConvertTo-Json) | Out-File -FilePath $marker -Encoding utf8 -Force
    L "Marker        : $marker"
} catch {
    L "  TASK REGISTRATION FAILED -> $($_.Exception.Message)"
    exit 1
}

L "DONE. Reboot once to verify; read C:\ProgramData\BTGuard\bt-guard.log afterwards."
